/*
 * Exports every question (answers, hints, explanations, why-wrong notes)
 * from js/questions.js into a readable QUESTION_BANK.md for teacher review.
 *
 * Run from the project folder:   node tools/export-question-bank.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { PAGES } = require('../js/questions.js');

const L = ['A', 'B', 'C', 'D'];
const lines = [];
lines.push('# Code Quest · Question Bank (TEMPORARY demonstration questions, 4 pages × 5)');
lines.push('');
lines.push('> Generated from `js/questions.js` by `tools/export-question-bank.js`. Do not edit this file by hand;');
lines.push('> edit `js/questions.js` and run the script again. These questions exist to test the engine and are');
lines.push('> **not** the final assessment. Items marked ⚠ are covered in `TEACHER_NOTES.md`.');
lines.push('');

PAGES.forEach((page) => {
  lines.push(`## Section ${page.section} · Page ${page.id}: ${page.title}`);
  lines.push('');
  page.questions.forEach((q, n) => {
    lines.push(`### ${page.id}.${n + 1} · ${q.concept}  \`${q.id}\``);
    lines.push('');
    lines.push(`**${q.prompt}**`);
    lines.push('');
    if (q.code) {
      lines.push('```python');
      lines.push(q.code);
      lines.push('```');
      lines.push('');
    }
    const ans = Array.isArray(q.answer) ? q.answer : [q.answer];
    if (q.type === 'multi') { lines.push(`*Multiple-select: ${ans.length} correct answers, all-or-nothing.*`); lines.push(''); }
    q.options.forEach((o, i) => {
      const mark = ans.indexOf(i) !== -1 ? ' ✅ **correct**' : '';
      const text = q.optionsAreCode ? '`' + o + '`' : o;
      lines.push(`- ${L[i]}. ${text}${mark}`);
    });
    lines.push('');
    lines.push(`- **Hint after wrong attempt 1:** ${q.hints[0]}`);
    lines.push(`- **Hint after wrong attempt 2:** ${q.hints[1]}`);
    lines.push(`- **Explanation:** ${q.explanation}`);
    q.options.forEach((o, i) => {
      if (ans.indexOf(i) === -1) lines.push(`- **If a student picks ${L[i]}:** ${q.whyWrong[i]}`);
    });
    lines.push('');
  });
});

const target = path.join(__dirname, '..', 'QUESTION_BANK.md');
fs.writeFileSync(target, lines.join('\n'), 'utf8');
console.log('Wrote ' + target + ' (' + lines.length + ' lines)');
